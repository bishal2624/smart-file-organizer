"""Core file organization logic for Smart File Organizer.

This module implements directory scanning, category resolution, collision-free
destination planning, path validation, and file moving operations.
It is strictly decoupled from the graphical user interface and imports no GUI modules.
Files are moved one file at a time, with the destination re-checked immediately
before each move and each move wrapped in its own try/except block.
"""

from datetime import datetime
import os
from pathlib import Path
import shutil
import sys
from typing import Any, Callable, Dict, List, Optional, Set, Tuple

from config import (
    ALL_CATEGORIES,
    APP_SOURCE_FILES,
    DEFAULT_CATEGORY,
    EXCLUDED_FILENAMES,
    EXCLUDED_PREFIXES,
    EXCLUDED_SUFFIXES,
    EXTENSION_MAP,
)
from logger import log_event, save_report


def get_category(path: Path) -> str:
    """Return the category name for a given file path based on its lowercase suffix.

    Args:
        path: Path object representing the file.

    Returns:
        String representing the matching category name, or DEFAULT_CATEGORY.
    """
    ext = path.suffix.lower()
    if not ext:
        return DEFAULT_CATEGORY
    return EXTENSION_MAP.get(ext, DEFAULT_CATEGORY)


def is_system_critical_folder(path: Path) -> Tuple[bool, str]:
    """Check if the provided path is a protected or system-critical location.

    Args:
        path: Resolved absolute Path to check.

    Returns:
        Tuple of (is_critical, explanation_message).
    """
    resolved = path.resolve()

    # Refuse root of any drive (e.g., C:\ or /)
    if resolved.parent == resolved or len(resolved.parts) <= 1:
        return True, "Cannot organize the root of a drive. Please select a specific folder."

    # Refuse user profile root (e.g., C:\Users\Username or /home/username)
    try:
        home_path = Path.home().resolve()
        if resolved == home_path:
            return True, "Cannot organize the user profile root directory directly. Please select a subfolder such as Downloads."
    except RuntimeError:
        pass

    # Windows-specific system paths
    if sys.platform.startswith("win"):
        env_vars = ["SystemRoot", "WINDIR", "ProgramFiles", "ProgramFiles(x86)", "ProgramData"]
        for var in env_vars:
            val = os.environ.get(var)
            if val:
                crit_path = Path(val).resolve()
                if resolved == crit_path or crit_path in resolved.parents:
                    return True, f"Selected folder is inside a protected Windows directory ({var})."

    return False, ""


def validate_folder(folder_path: Path) -> Tuple[bool, str]:
    """Validate that a selected folder exists, is a directory, and is safe and accessible.

    Args:
        folder_path: Path to validate.

    Returns:
        Tuple of (is_valid, error_message). If valid, error_message is empty.
    """
    if not folder_path.exists():
        return False, "The selected path does not exist. Please choose a valid directory."

    if not folder_path.is_dir():
        return False, "The selected path is a file, not a directory. Please choose a folder."

    # Verify read access
    try:
        next(folder_path.iterdir(), None)
    except PermissionError:
        return False, "Read access denied. The application cannot inspect this folder."
    except OSError as err:
        return False, f"Folder cannot be accessed: {str(err)}"

    # Verify write access by checking permissions
    if not os.access(folder_path, os.W_OK):
        return False, "Write access denied. The application requires write permission to organize files."

    # Check against system-critical folder constraints
    is_critical, reason = is_system_critical_folder(folder_path)
    if is_critical:
        return False, reason

    return True, ""


def should_skip_file(file_path: Path, root_folder: Path) -> bool:
    """Determine whether an individual file should be excluded from organization.

    Args:
        file_path: Path to the candidate file.
        root_folder: Root directory selected by the user.

    Returns:
        True if the file must be skipped, False if it should be processed.
    """
    # Never process symbolic links
    if file_path.is_symlink():
        return True

    name = file_path.name
    name_lower = name.lower()

    # Skip hidden files
    for prefix in EXCLUDED_PREFIXES:
        if name.startswith(prefix):
            return True

    # Skip temporary files
    for suffix in EXCLUDED_SUFFIXES:
        if name_lower.endswith(suffix):
            return True

    # Skip known system and log files
    if name_lower in EXCLUDED_FILENAMES:
        return True

    # Skip JSON report files generated by this tool
    if name_lower.startswith("report_") and name_lower.endswith(".json"):
        return True

    # Skip source files if user targets the project directory itself
    if name_lower in APP_SOURCE_FILES:
        return True

    return False


def scan_folder(folder: Path, include_subfolders: bool = False) -> List[Path]:
    """Scan the target folder and return a list of eligible files to organize.

    Args:
        folder: Path of the folder to scan.
        include_subfolders: If True, also scan subfolders (excluding category folders).

    Returns:
        List of Path objects for all eligible candidate files.
    """
    valid_files: List[Path] = []
    category_set: Set[str] = set(ALL_CATEGORIES)

    try:
        if not include_subfolders:
            # Non-recursive: inspect top-level contents only
            for item in folder.iterdir():
                if item.is_file() and not should_skip_file(item, folder):
                    valid_files.append(item)
        else:
            # Recursive scanning: walk subdirectories safely
            for root_dir, dirs, files in os.walk(folder):
                current_path = Path(root_dir)

                # Prevent descending into any category folders
                dirs[:] = [d for d in dirs if d not in category_set]

                for filename in files:
                    file_path = current_path / filename
                    if should_skip_file(file_path, folder):
                        continue

                    # Skip files that are already inside their matching category folder
                    assigned_category = get_category(file_path)
                    if file_path.parent.name == assigned_category:
                        continue

                    valid_files.append(file_path)
    except (OSError, PermissionError):
        pass

    return valid_files


def unique_destination(dest_path: Path, reserved_paths: Set[str]) -> Path:
    """Resolve duplicate filenames by appending a numeric counter, e.g., 'report (1).pdf'.

    This checks both physical disk presence and names already reserved by earlier
    items in the same plan to ensure zero collisions.

    Args:
        dest_path: Preferred destination path.
        reserved_paths: Set of lowercase string representations of paths reserved in current plan.

    Returns:
        A unique destination Path that does not collide with existing or planned files.
    """
    target_dir = dest_path.parent
    stem = dest_path.stem
    suffix = dest_path.suffix

    candidate = dest_path
    counter = 1

    def is_occupied(path_to_test: Path) -> bool:
        # Check against files already on disk or already reserved in this execution run
        path_str_key = str(path_to_test.resolve()).lower()
        return path_to_test.exists() or path_str_key in reserved_paths

    while is_occupied(candidate):
        candidate = target_dir / f"{stem} ({counter}){suffix}"
        counter += 1

    reserved_paths.add(str(candidate.resolve()).lower())
    return candidate


def build_plan(files: List[Path], root_folder: Path) -> List[Dict[str, Any]]:
    """Generate a collision-free execution plan for moving the given files.

    This function does not alter files or directories on disk.

    Args:
        files: List of file paths to plan for.
        root_folder: Root folder where category subfolders will reside.

    Returns:
        A list of plan entry dictionaries containing file details and destinations.
    """
    plan: List[Dict[str, Any]] = []
    reserved_destinations: Set[str] = set()

    for file_path in files:
        category = get_category(file_path)
        dest_folder = root_folder / category
        preferred_dest = dest_folder / file_path.name

        # If the file is already in its designated destination, flag it as skipped
        try:
            if file_path.resolve() == preferred_dest.resolve():
                plan.append({
                    "filename": file_path.name,
                    "extension": file_path.suffix.lower() if file_path.suffix else "(none)",
                    "category": category,
                    "source": file_path,
                    "destination": preferred_dest,
                    "dest_filename": preferred_dest.name,
                    "is_renamed": False,
                    "is_skip": True,
                    "skip_reason": "File is already in its designated category folder.",
                })
                continue
        except OSError:
            pass

        # Resolve any duplicates on disk or within the planned batch
        final_dest = unique_destination(preferred_dest, reserved_destinations)
        is_renamed = final_dest.name != file_path.name

        plan.append({
            "filename": file_path.name,
            "extension": file_path.suffix.lower() if file_path.suffix else "(none)",
            "category": category,
            "source": file_path,
            "destination": final_dest,
            "dest_filename": final_dest.name,
            "is_renamed": is_renamed,
            "is_skip": False,
            "skip_reason": "",
        })

    return plan


def execute_plan(
    plan: List[Dict[str, Any]],
    root_folder: Path,
    progress_callback: Optional[Callable[[int, int, str], None]] = None,
    cancel_check: Optional[Callable[[], bool]] = None,
) -> Dict[str, Any]:
    """Execute the movement plan one file at a time with strict safety guards.

    Each move is verified immediately beforehand and executed individually inside
    its own try/except block. Category directories are created on demand.
    No file is ever deleted, truncated, or overwritten.

    Args:
        plan: List of plan entry dictionaries generated by build_plan.
        root_folder: The root directory being organized.
        progress_callback: Function receiving (current_index, total_count, message).
        cancel_check: Callable returning True if the user requested cancellation.

    Returns:
        Results summary dictionary containing counts, statuses, and failures.
    """
    total_files = len(plan)
    moved_count = 0
    skipped_count = 0
    failed_count = 0
    category_counts: Dict[str, int] = {cat: 0 for cat in ALL_CATEGORIES}
    file_statuses: List[Dict[str, Any]] = []
    failures: List[Dict[str, str]] = []

    start_time = datetime.now()
    log_event("SESSION_START", str(root_folder), "", "", "INFO", f"Beginning organization of {total_files} planned items.")

    for idx, entry in enumerate(plan, start=1):
        # Respond immediately to user cancellation request
        if cancel_check and cancel_check():
            log_event("CANCEL", entry["filename"], str(entry["source"]), "", "WARNING", "Operation cancelled by user.")
            skipped_count += (total_files - idx + 1)
            break

        source_path: Path = entry["source"]
        dest_path: Path = entry["destination"]
        category: str = entry["category"]
        filename: str = entry["filename"]

        if progress_callback:
            progress_callback(idx, total_files, f"Moving {idx} of {total_files}: {filename}")

        # Handle items identified for skipping during planning
        if entry.get("is_skip", False):
            skipped_count += 1
            reason = entry.get("skip_reason", "Already in position.")
            log_event("SKIP", filename, str(source_path), str(dest_path), "SKIPPED", reason)
            file_statuses.append({
                "filename": filename,
                "status": "SKIPPED",
                "message": reason,
                "destination": str(dest_path),
            })
            continue

        # Immediate pre-flight check 1: source must exist
        if not source_path.exists():
            failed_count += 1
            err_msg = "Source file no longer exists on disk."
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})
            continue

        # Immediate pre-flight check 2: destination must not already exist (never overwrite)
        if dest_path.exists():
            failed_count += 1
            err_msg = "Target file already exists unexpectedly. Move aborted to avoid overwrite."
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})
            continue

        # Create destination directory only when needed
        try:
            dest_path.parent.mkdir(parents=True, exist_ok=True)
        except (PermissionError, OSError) as dir_err:
            failed_count += 1
            err_msg = f"Could not create category folder: {str(dir_err)}"
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})
            continue

        # Execute move for this single file with isolated exception handling
        try:
            shutil.move(str(source_path), str(dest_path))
            moved_count += 1
            category_counts[category] = category_counts.get(category, 0) + 1
            log_event("MOVE", filename, str(source_path), str(dest_path), "SUCCESS", "Moved successfully.")
            file_statuses.append({
                "filename": filename,
                "status": "SUCCESS",
                "message": "Moved successfully.",
                "destination": str(dest_path),
            })
        except PermissionError:
            failed_count += 1
            err_msg = "Permission denied. The file may be in use by another application or read-only."
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})
        except FileNotFoundError:
            failed_count += 1
            err_msg = "File was removed or renamed by another process during execution."
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})
        except OSError as os_err:
            failed_count += 1
            err_msg = f"System error during file transfer: {str(os_err)}"
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})
        except Exception as generic_err:
            failed_count += 1
            err_msg = f"Unexpected error during move: {str(generic_err)}"
            log_event("MOVE", filename, str(source_path), str(dest_path), "FAILED", err_msg)
            failures.append({"filename": filename, "reason": err_msg})
            file_statuses.append({"filename": filename, "status": "FAILED", "message": err_msg, "destination": str(dest_path)})

    end_time = datetime.now()

    results: Dict[str, Any] = {
        "folder": str(root_folder),
        "start_time": start_time.strftime("%Y-%m-%d %H:%M:%S"),
        "end_time": end_time.strftime("%Y-%m-%d %H:%M:%S"),
        "total_files": total_files,
        "moved": moved_count,
        "skipped": skipped_count,
        "failed": failed_count,
        "category_counts": category_counts,
        "failures": failures,
        "file_statuses": file_statuses,
    }

    # Save summary report JSON to logs directory
    report_file = save_report(results)
    results["report_file"] = str(report_file) if report_file else ""
    log_event("SESSION_END", str(root_folder), "", "", "INFO", f"Run complete. Moved: {moved_count}, Skipped: {skipped_count}, Failed: {failed_count}.")

    return results
